namespace Saw2Launcher.Services;

/// <summary>
/// Launcher UI strings follow the selected game language (en/it/de/fr/es).
/// </summary>
public sealed class LauncherLocale
{
    public string Code { get; }
    private readonly Dictionary<string, string> _t;

    private LauncherLocale(string code, Dictionary<string, string> t)
    {
        Code = code;
        _t = t;
    }

    public string this[string key] =>
        _t.TryGetValue(key, out var v) ? v : (En._t.TryGetValue(key, out var e) ? e : key);

    public string Fmt(string key, params object[] args) => string.Format(this[key], args);

    public static LauncherLocale FromGameLanguageId(uint id) => id switch
    {
        3 => De,
        4 => Fr,
        5 => Es,
        6 => It,
        _ => En,
    };

    public static LauncherLocale FromCode(string? code) => (code ?? "en").ToLowerInvariant() switch
    {
        "it" => It,
        "de" => De,
        "fr" => Fr,
        "es" => Es,
        _ => En,
    };

    public string LangDisplayName(uint id) => id switch
    {
        1 => this["lang.en"],
        3 => this["lang.de"],
        4 => this["lang.fr"],
        5 => this["lang.es"],
        6 => this["lang.it"],
        _ => this["lang.en"],
    };

