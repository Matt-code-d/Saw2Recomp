    private static Dictionary<string, string> Merge(Dictionary<string, string> baseDict, Dictionary<string, string> over)
    {
        var d = new Dictionary<string, string>(baseDict, StringComparer.Ordinal);
        foreach (var kv in over) d[kv.Key] = kv.Value;
        return d;
    }
